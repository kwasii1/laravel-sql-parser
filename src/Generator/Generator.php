/**
 * Turns expression trees into SQL (a port of sqlglot's Generator).
 *
 * Each node class is generated by, in order: its TRANSFORMS entry, a `<key>Sql()` method (the
 * node's KEY, e.g. selectSql() for Select), or the generic function / property fallback.
 * Dialect generators extend this class and point TABLES at their generated tables class.
 */
class Generator
{
    use Concerns\DialectHelpers;
    use Concerns\GeneratesExpressions;
    use Concerns\GeneratesFunctions;
    use Concerns\GeneratesQueries;
    use Concerns\GeneratesStatements;
    use Concerns\HandlesTransforms;
    use Concerns\Transforms;

    /** @var class-string */
    public const string TABLES = GeneratorTables::class;

    public const string SENTINEL_LINE_BREAK = '__SQLGLOT__LB__';

    public bool $pretty = false;

    /** Quote identifiers: false (only when required), true (always), 'safe' or 'unsafe'. */
    public bool|string $identify = false;

    public bool $normalize = false;

    public int $pad = 2;

    public int $indentSize = 2;

    public bool|string $normalizeFunctions;

    public ErrorLevel $unsupportedLevel = ErrorLevel::Warn;

    public int $maxUnsupported = 3;

    public bool $leadingComma = false;

    public int $maxTextWidth = 80;

    public bool $comments = true;

    /** @var list<string> */
    public array $unsupportedMessages = [];

    /** @var array<string, mixed> every constant of static::TABLES */
    protected array $t;

    protected string $escapedQuoteEnd;

    protected string $escapedByteQuoteEnd;

    protected string $escapedIdentifierEnd;

    protected string $identifierStart;

    protected string $identifierEnd;

    protected bool $quoteJsonPathKeyUsingBrackets = true;

    private int $nameCounter = 0;

    /** @var array<class-string, Closure(Expression): string|false> */
    private array $dispatch = [];

    /** @var array<class-string, array<string, mixed>> */
    private static array $tableCache = [];

    /** Generator options: sqlglot's names (snake_case) and their camelCase spellings. */
    private const array OPTION_ALIASES = [
        'normalize_functions' => 'normalizeFunctions',
        'unsupported_level' => 'unsupportedLevel',
        'max_unsupported' => 'maxUnsupported',
        'leading_comma' => 'leadingComma',
        'max_text_width' => 'maxTextWidth',
        'indent' => 'indentSize',
    ];

    /**
     * @param  array<string, mixed>  $options
     */
    public function __construct(public readonly Dialect $dialect, array $options = [])
    {
        $this->t = self::$tableCache[static::TABLES] ??= (new ReflectionClass(static::TABLES))->getConstants();
        $this->normalizeFunctions = $dialect->settings['NORMALIZE_FUNCTIONS'];

        foreach ($options as $name => $value) {
            $property = self::OPTION_ALIASES[$name] ?? $name;

            match ($property) {
                'pretty' => $this->pretty = (bool) $value,
                'identify' => $this->identify = is_string($value) ? $value : (bool) $value,
                'normalize' => $this->normalize = (bool) $value,
                'pad' => $this->pad = (int) $value,
                'indentSize' => $this->indentSize = (int) $value,
                'normalizeFunctions' => $this->normalizeFunctions = $value === null ? $dialect->settings['NORMALIZE_FUNCTIONS'] : (is_string($value) ? $value : (bool) $value),
                'unsupportedLevel' => $this->unsupportedLevel = $value instanceof ErrorLevel ? $value : ErrorLevel::from(strtolower((string) $value)),
                'maxUnsupported' => $this->maxUnsupported = (int) $value,
                'leadingComma' => $this->leadingComma = (bool) $value,
                'maxTextWidth' => $this->maxTextWidth = (int) $value,
                'comments' => $this->comments = (bool) $value,
                default => throw new InvalidArgumentException("Unknown generator option '{$name}'."),
            };
        }

        $stringEscapes = $dialect->tokenizerTable('STRING_ESCAPES_LIST');
        $firstEscape = (string) ($stringEscapes[0] ?? "'");
        $byteEnd = $dialect->settings['BYTE_END'];

        $this->escapedQuoteEnd = $firstEscape.$dialect->settings['QUOTE_END'];
        $this->escapedByteQuoteEnd = is_string($byteEnd) && $byteEnd !== '' ? $firstEscape.$byteEnd : '';
        $this->identifierStart = (string) $dialect->settings['IDENTIFIER_START'];
        $this->identifierEnd = (string) $dialect->settings['IDENTIFIER_END'];
        $this->escapedIdentifierEnd = $this->identifierEnd.$this->identifierEnd;
    }

    /**
     * Generate the SQL for an expression tree.
     *
     * @param  bool  $copy  generation mutates the tree, so it's copied first unless this is false
     */
    public function generate(Expression $expression, bool $copy = true): string
    {
        if ($copy) {
            $expression = $expression->copy();
        }

        $expression = $this->preprocess($expression);

        $this->unsupportedMessages = [];
        $sql = trim($this->sql($expression), " \t\n\r\0\x0B\f");

        if ($this->pretty) {
            $sql = str_replace(self::SENTINEL_LINE_BREAK, "\n", $sql);
        }

        $this->reportUnsupported();

        return $sql;
    }

    /**
     * Warn about or raise the unsupported messages collected while generating, per unsupportedLevel.
     */
    protected function reportUnsupported(): void
    {
        $messages = $this->unsupportedMessages;

        if ($this->unsupportedLevel === ErrorLevel::Warn) {
            foreach ($messages as $message) {
                Parser::warn($message);
            }
        } elseif ($this->unsupportedLevel === ErrorLevel::Raise && $messages !== []) {
            $remaining = count($messages) - $this->maxUnsupported;
            $messages = array_slice($messages, 0, $this->maxUnsupported);

            if ($remaining > 0) {
                $messages[] = "... and {$remaining} more";
            }

            throw new UnsupportedError(implode("\n\n", $messages));
        }
    }

    /**
     * Apply generic preprocessing transformations to an expression.
     */
    public function preprocess(Expression $expression): Expression
    {
        $expression = $this->moveCtesToTopLevelIfNeeded($expression);

        if ($this->t['ENSURE_BOOLS'] === true) {
            $expression = $this->ensureBools($expression);
        }

        return $expression;
    }

    protected function moveCtesToTopLevelIfNeeded(Expression $expression): Expression
    {
        if ($expression->parent !== null || ! isset($this->t['EXPRESSIONS_WITHOUT_NESTED_CTES'][$expression::class])) {
            return $expression;
        }

        foreach ($expression->findAll(With::class) as $with) {
            if ($with->parent !== $expression) {
                return $this->moveCtesToTopLevel($expression);
            }
        }

        return $expression;
    }

    public function unsupported(string $message): void
    {
        if ($this->unsupportedLevel === ErrorLevel::Immediate) {
            throw new UnsupportedError($message);
        }

        $this->unsupportedMessages[] = $message;
    }

    public function sep(string $sep = ' '): string
    {
        return $this->pretty ? trim($sep)."\n" : $sep;
    }

    public function seg(string $sql, string $sep = ' '): string
    {
        return $this->sep($sep).$sql;
    }

    protected function sanitizeComment(string $comment): string
    {
        if ($comment !== '' && trim($comment[0]) !== '') {
            $comment = ' '.$comment;
        }

        if ($comment !== '' && trim($comment[strlen($comment) - 1]) !== '') {
            $comment .= ' ';
        }

        // Escape block comment markers to prevent premature closure or unintended nesting.
        return str_replace(['*/', '/*'], ['* /', '/ *'], $comment);
    }

    /**
     * Append (or prepend) an expression's comments to its SQL.
     *
     * @param  list<string>|null  $comments
     */
    public function maybeComment(string $sql, ?Expression $expression = null, ?array $comments = null, bool $separated = false): string
    {
        if (! $this->comments) {
            return $sql;
        }

        $comments ??= $expression?->comments;

        if ($comments === null || $comments === [] || ($expression !== null && $this->isInstanceOfAny($expression, $this->t['EXCLUDE_COMMENTS']))) {
            return $sql;
        }

        $commentsList = [];
        foreach ($comments as $comment) {
            if ($comment !== '') {
                $commentsList[] = '/*'.$this->replaceLineBreaks($this->sanitizeComment($comment)).'*/';
            }
        }

        if ($commentsList === []) {
            return $sql;
        }

        if ($separated || ($expression !== null && $this->isInstanceOfAny($expression, $this->t['WITH_SEPARATED_COMMENTS']))) {
            $commentsSql = implode($this->sep(), $commentsList);

            return $sql === '' || ctype_space($sql[0])
                ? $this->sep().$commentsSql.$sql
                : $commentsSql.$this->sep().$sql;
        }

        return $sql.' '.implode(' ', $commentsList);
    }

    /**
     * @param  array<array-key, mixed>  $classes  a list of class names, or a set keyed by them
     */
    protected function isInstanceOfAny(Expression $expression, array $classes): bool
    {
        foreach ($classes as $key => $class) {
            $class = is_string($key) ? $key : $class;

            if (is_string($class) && $expression instanceof $class) {
                return true;
            }
        }

        return false;
    }

    public function wrap(Expression|string $expression): string
    {
        $thisSql = $expression instanceof Select || $expression instanceof SetOperation
            ? $this->sql($expression)
            : $this->sql($expression, 'this');

        if ($thisSql === '') {
            return '()';
        }

        $thisSql = $this->indent($thisSql, level: 1, pad: 0);

        return '('.$this->sep('').$thisSql.$this->seg(')', sep: '').'';
    }

    /**
     * Run a callback with identifier quoting turned off.
     *
     * @template T
     *
     * @param  Closure(): T  $callback
     * @return T
     */
    public function noIdentify(Closure $callback): mixed
    {
        $original = $this->identify;
        $this->identify = false;

        try {
            return $callback();
        } finally {
            $this->identify = $original;
        }
    }

    public function normalizeFunc(string $name): string
    {
        if ($this->normalizeFunctions === 'upper' || $this->normalizeFunctions === true) {
            return strtoupper($name);
        }

        if ($this->normalizeFunctions === 'lower') {
            return strtolower($name);
        }

        return $name;
    }

    public function indent(string $sql, int $level = 0, ?int $pad = null, bool $skipFirst = false, bool $skipLast = false): string
    {
        if (! $this->pretty || $sql === '') {
            return $sql;
        }

        $pad ??= $this->pad;
        $prefix = str_repeat(' ', $level * $this->indentSize + $pad);
        $lines = explode("\n", $sql);
        $last = count($lines) - 1;

        foreach ($lines as $i => $line) {
            if (! (($skipFirst && $i === 0) || ($skipLast && $i === $last))) {
                $lines[$i] = $prefix.$line;
            }
        }

        return implode("\n", $lines);
    }

    /**
     * Generate SQL for an expression, an argument of an expression ($key), or pass a string through.
     */
    public function sql(Expression|string|null $expression, ?string $key = null, bool $comment = true): string
    {
        if ($expression === null || $expression === '') {
            return '';
        }

        if (is_string($expression)) {
            return $expression;
        }

        if ($key !== null) {
            $value = $expression->args[$key] ?? null;

            if ($value instanceof Expression) {
                return $this->sql($value);
            }

            if (is_string($value)) {
                return $value;
            }

            if (is_int($value) || is_float($value)) {
                return (string) $value;
            }

            return '';
        }

        $handler = $this->dispatch[$expression::class] ??= $this->resolveHandler($expression::class);

        if ($handler !== false) {
            $sql = $handler($expression);
        } elseif ($expression instanceof Func) {
            $sql = $this->functionFallbackSql($expression);
        } elseif ($expression instanceof Property) {
            $sql = $this->propertySql($expression);
        } else {
            throw new InvalidArgumentException('Unsupported expression type '.(new ReflectionClass($expression))->getShortName());
        }

        // Checked here first: almost no node has comments, and this runs for every node
        return $this->comments && $comment && $expression->comments !== null && $expression->comments !== []
            ? $this->maybeComment($sql, $expression)
            : $sql;
    }

    /**
     * @param  class-string<Expression>  $class
     * @return (Closure(Expression): string)|false
     */
    private function resolveHandler(string $class): Closure|false
    {
        $handler = $this->t['TRANSFORMS'][$class] ?? null;

        if ($handler !== null) {
            return fn (Expression $e): string => $this->callTransform($handler, $e);
        }

        $method = $class::KEY.'Sql';

        if (method_exists($this, $method)) {
            return $this->{$method}(...);
        }

        return false;
    }

    /**
     * @param  string|array<int|string, mixed>  $handler
     */
    protected function callTransform(string|array $handler, Expression $expression): string
    {
        if (is_array($handler)) {
            $method = $handler[0];
            unset($handler[0]);

            // An ['@literal' => text, 'is_string' => bool] entry stands for an exp.Literal
            foreach ($handler as $name => $value) {
                if (is_array($value) && isset($value['@literal'])) {
                    $handler[$name] = $value['is_string'] === true ? Literal::string((string) $value['@literal']) : Literal::number((string) $value['@literal']);
                }
            }

            return $this->{$method}($expression, ...$handler);
        }

        return $this->{$handler}($expression);
    }

    /**
     * Generate a list of expressions (an argument, or the given SQL strings / expressions).
     *
     * @param  list<Expression|string>|null  $sqls
     */
    public function expressions(
        ?Expression $expression = null,
        ?string $key = null,
        ?array $sqls = null,
        bool $flat = false,
        bool $indent = true,
        bool $skipFirst = false,
        bool $skipLast = false,
        string $sep = ', ',
        string $prefix = '',
        bool $dynamic = false,
        bool $newLine = false,
    ): string {
        $expressions = $expression !== null ? ($expression->args[$key ?? 'expressions'] ?? null) : $sqls;

        if (! is_array($expressions) || $expressions === []) {
            return '';
        }

        if ($flat) {
            $parts = [];
            foreach ($expressions as $e) {
                $sql = $this->sql($e);

                if ($sql !== '') {
                    $parts[] = $sql;
                }
            }

            return implode($sep, $parts);
        }

        $numSqls = count($expressions);
        $resultSqls = [];

        foreach (array_values($expressions) as $i => $e) {
            $sql = $this->sql($e, comment: false);

            if ($sql === '') {
                continue;
            }

            $comments = $e instanceof Expression ? $this->maybeComment('', $e) : '';

            if ($this->pretty) {
                if ($this->leadingComma) {
                    $resultSqls[] = ($i > 0 ? $sep : '').$prefix.$sql.$comments;
                } else {
                    $resultSqls[] = $prefix.$sql.($i + 1 < $numSqls ? ($comments !== '' ? rtrim($sep) : $sep) : '').$comments;
                }
            } else {
                $resultSqls[] = $prefix.$sql.$comments.($i + 1 < $numSqls ? $sep : '');
            }
        }

        if ($this->pretty && (! $dynamic || $this->tooWide($resultSqls))) {
            if ($newLine) {
                array_unshift($resultSqls, '');
                $resultSqls[] = '';
            }

            $resultSql = implode("\n", array_map('rtrim', $resultSqls));
        } else {
            $resultSql = implode('', $resultSqls);
        }

        return $indent ? $this->indent($resultSql, skipFirst: $skipFirst, skipLast: $skipLast) : $resultSql;
    }

    public function opExpressions(string $op, Expression $expression, bool $flat = false): string
    {
        $flat = $flat || $expression->parent instanceof Properties;
        $expressionsSql = $this->expressions($expression, flat: $flat);

        if ($flat) {
            return "{$op} {$expressionsSql}";
        }

        return $this->seg($op).($expressionsSql !== '' ? $this->sep() : '').$expressionsSql;
    }

    public function nakedProperty(Expression $expression): string
    {
        $propertyName = Properties::PROPERTY_TO_NAME[$expression::class] ?? null;

        if ($propertyName === null) {
            $this->unsupported('Unsupported property '.(new ReflectionClass($expression))->getShortName());
        }

        return ($propertyName ?? 'None').' '.$this->sql($expression, 'this');
    }

    public function tokenSql(int $tokenType): string
    {
        return $this->t['TOKEN_MAPPING'][$tokenType] ?? TokenType::name($tokenType);
    }

    /**
     * Join the non-empty strings.
     */
    public static function csv(string ...$args): string
    {
        return self::csvWith(', ', ...$args);
    }

    public static function csvWith(string $sep, string ...$args): string
    {
        return implode($sep, array_filter($args, static fn (string $arg): bool => $arg !== ''));
    }

    /**
     * Generate a function call. Null and bool arguments are skipped.
     */
    public function func(string $name, mixed ...$args): string
    {
        return $this->funcWith($name, array_values($args));
    }

    /**
     * @param  list<mixed>  $args
     */
    public function funcWith(string $name, array $args, string $prefix = '(', string $suffix = ')', bool $normalize = true): string
    {
        $name = $normalize ? $this->normalizeFunc($name) : $name;

        return $name.$prefix.$this->formatArgs($args).$suffix;
    }

    /**
     * @param  list<mixed>  $args
     */
    public function formatArgs(array $args, string $sep = ', '): string
    {
        $argSqls = [];

        foreach ($args as $arg) {
            if ($arg !== null && ! is_bool($arg)) {
                $argSqls[] = $arg instanceof Expression ? $this->sql($arg) : (string) $arg;
            }
        }

        if ($this->pretty && $this->tooWide($argSqls)) {
            return $this->indent("\n".implode(trim($sep)."\n", $argSqls)."\n", skipFirst: true, skipLast: true);
        }

        return implode($sep, $argSqls);
    }

    /**
     * @param  list<string>  $args
     */
    public function tooWide(array $args): bool
    {
        $length = 0;

        foreach ($args as $arg) {
            $length += mb_strlen($arg, 'UTF-8');
        }

        return $length > $this->maxTextWidth;
    }

    /**
     * Generate a binary operator, iteratively for chains of the same operator (e.g. a AND b AND c).
     */
    public function binary(Expression $expression, string $op): string
    {
        $sqls = [];
        $stack = [$expression];
        $binaryType = $expression::class;

        while ($stack !== []) {
            $node = array_pop($stack);

            if ($node instanceof Expression && $node::class === $binaryType) {
                $opFunc = $node->args['operator'] ?? null;

                if ($opFunc !== null && $opFunc !== '' && $opFunc !== false) {
                    $op = 'OPERATOR('.$this->sql($opFunc).')';
                }

                $stack[] = $node->args['expression'] ?? null;
                $stack[] = ' '.$this->maybeComment($op, comments: $node->comments).' ';
                $stack[] = $node->args['this'] ?? null;
            } else {
                $sqls[] = $this->sql($node);
            }
        }

        return implode('', $sqls);
    }

    public function functionFallbackSql(Expression $expression): string
    {
        $args = [];

        foreach (array_keys($expression::ARG_TYPES) as $key) {
            $argValue = $expression->args[$key] ?? null;

            if (is_array($argValue)) {
                foreach ($argValue as $value) {
                    $args[] = $value;
                }
            } elseif ($argValue !== null) {
                $args[] = $argValue;
            }
        }

        if ($this->dialect->settings['PRESERVE_ORIGINAL_NAMES'] === true) {
            $name = $expression->metaGet('name');
            $name = is_string($name) && $name !== '' ? $name : $expression::sqlName();
        } else {
            $name = $expression::sqlName();
        }

        return $this->funcWith($name, $args);
    }

    public function queryModifiers(Expression $expression, string ...$sqls): string
    {
        $limit = $expression->args['limit'] ?? null;

        if ($this->t['LIMIT_FETCH'] === 'LIMIT' && $limit instanceof Fetch) {
            $count = $limit->args['count'] ?? null;
            // "FETCH FIRST ROWS ONLY" without a count means one row per the SQL standard
            $limit = new Limit(['expression' => $count instanceof Expression ? $count->copy() : Literal::number(1)]);
        } elseif ($this->t['LIMIT_FETCH'] === 'FETCH' && $limit instanceof Limit) {
            $limitExpression = $limit->args['expression'] ?? null;
            $limit = new Fetch(['direction' => 'FIRST', 'count' => $limitExpression instanceof Expression ? $limitExpression->copy() : null]);
        }

        $parts = $sqls;

        foreach ($expression->argList('joins') as $join) {
            $parts[] = $this->sql($join);
        }

        $parts[] = $this->sql($expression, 'match');

        foreach ($expression->argList('laterals') as $lateral) {
            $parts[] = $this->sql($lateral);
        }

        $parts[] = $this->sql($expression, 'prewhere');
        $parts[] = $this->sql($expression, 'where');
        $parts[] = $this->sql($expression, 'connect');
        $parts[] = $this->sql($expression, 'group');
        $parts[] = $this->sql($expression, 'having');

        foreach ($this->t['AFTER_HAVING_MODIFIER_TRANSFORMS'] as $handler) {
            $parts[] = $this->callTransform($handler, $expression);
        }

        $parts[] = $this->sql($expression, 'order');
        array_push($parts, ...$this->offsetLimitModifiers($expression, $limit instanceof Fetch, $limit instanceof Expression ? $limit : null));
        array_push($parts, ...$this->afterLimitModifiers($expression));
        $parts[] = $this->sql($expression, 'for_');
        $parts[] = $this->optionsModifier($expression);

        return self::csvWith('', ...$parts);
    }

    /**
     * @return list<string>
     */
    protected function offsetLimitModifiers(Expression $expression, bool $fetch, ?Expression $limit): array
    {
        return [
            $fetch ? $this->sql($expression, 'offset') : $this->sql($limit),
            $fetch ? $this->sql($limit) : $this->sql($expression, 'offset'),
        ];
    }

    /**
     * @return list<string>
     */
    protected function afterLimitModifiers(Expression $expression): array
    {
        $locks = $this->expressions($expression, key: 'locks', sep: ' ');
        $locks = $locks !== '' ? " {$locks}" : '';

        return [$locks, $this->sql($expression, 'sample')];
    }

    /**
     * sqlglot simplifies non-literal LIMIT/OFFSET values for dialects that only accept literals.
     * The optimizer isn't ported, so only constant integer arithmetic (+, -, *, parentheses and
     * negation) is folded; anything else is kept as it is.
     */
    protected function simplifyUnlessLiteral(?Expression $expression): ?Expression
    {
        if ($expression === null || $expression instanceof Literal) {
            return $expression;
        }

        $value = self::foldInteger($expression);

        return $value === null ? $expression : Literal::number($value);
    }

    private static function foldInteger(Expression $expression): ?int
    {
        if ($expression instanceof Literal) {
            return $expression->isInt() ? (int) $expression->name() : null;
        }

        if ($expression instanceof Paren || $expression instanceof Neg) {
            $inner = $expression->argExpr('this');
            $value = $inner !== null ? self::foldInteger($inner) : null;

            return $value === null ? null : ($expression instanceof Neg ? -$value : $value);
        }

        if ($expression instanceof Add || $expression instanceof Sub || $expression instanceof Mul) {
            $left = $expression->argExpr('this');
            $right = $expression->argExpr('expression');
            $a = $left !== null ? self::foldInteger($left) : null;
            $b = $right !== null ? self::foldInteger($right) : null;

            if ($a === null || $b === null) {
                return null;
            }

            return match (true) {
                $expression instanceof Add => $a + $b,
                $expression instanceof Sub => $a - $b,
                default => $a * $b,
            };
        }

        return null;
    }

    public function replaceLineBreaks(string $string): string
    {
        if ($this->pretty) {
            return str_replace("\n", self::SENTINEL_LINE_BREAK, $string);
        }

        return $string;
    }

    /**
     * A fresh internal name (_t0, _t1, ...).
     */
    protected function nextName(): string
    {
        return '_t'.$this->nameCounter++;
    }

    protected function truthy(mixed $value): bool
    {
        return $value !== null && $value !== false && $value !== '' && $value !== [] && $value !== 0;
    }
}
