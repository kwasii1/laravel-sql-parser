<?php

declare(strict_types=1);

namespace Tools\Generator;

use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use RuntimeException;

final class Support
{
    public const string GENERATED_MARKER = '@generated by tools/generate.php';

    public const string NAMESPACE = 'Kwasii\\LaravelSqlParser';

    /**
     * @return array{token_types: array<string, mixed>, expressions: array<string, mixed>, dialects: array<string, array<string, mixed>>}
     */
    public static function loadSpecs(string $directory): array
    {
        $dialects = [];

        foreach (glob($directory.'/dialects/*.json') ?: [] as $file) {
            $dialects[basename($file, '.json')] = self::readJson($file);
        }

        ksort($dialects);

        return [
            'token_types' => self::readJson($directory.'/token_types.json'),
            'expressions' => self::readJson($directory.'/expressions.json'),
            'dialects' => $dialects,
            'methods' => self::readJson($directory.'/methods.json')['methods'],
        ];
    }

    /**
     * @return array<string, mixed>
     */
    public static function readJson(string $file): array
    {
        $contents = file_get_contents($file);

        if ($contents === false) {
            throw new RuntimeException("Unable to read {$file}");
        }

        $data = json_decode($contents, true, 512, JSON_THROW_ON_ERROR);

        if (! is_array($data)) {
            throw new RuntimeException("Unexpected JSON in {$file}");
        }

        return $data;
    }

    /**
     * @return list<string>
     */
    public static function generatedFiles(string $directory): array
    {
        $files = [];
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory, RecursiveDirectoryIterator::SKIP_DOTS));

        foreach ($iterator as $file) {
            if ($file->isFile() && $file->getExtension() === 'php') {
                $head = (string) file_get_contents($file->getPathname(), false, null, 0, 600);

                if (str_contains($head, self::GENERATED_MARKER)) {
                    $files[] = $file->getPathname();
                }
            }
        }

        sort($files);

        return $files;
    }

    public static function fileHeader(string $namespace, string $source, array $uses = []): string
    {
        $header = "<?php\n\ndeclare(strict_types=1);\n\n// ".self::GENERATED_MARKER." from {$source}. Do not edit by hand.\n\nnamespace {$namespace};\n";

        if ($uses !== []) {
            sort($uses);
            $header .= "\n".implode('', array_map(static fn (string $use): string => "use {$use};\n", array_unique($uses)));
        }

        return $header;
    }

    /**
     * Export a value as a PHP literal using short array syntax.
     *
     * @param  array<array-key, string>  $comments  optional trailing comments keyed like $value
     */
    public static function export(mixed $value, int $indent = 1, array $comments = []): string
    {
        if (is_array($value)) {
            if ($value === []) {
                return '[]';
            }

            $pad = str_repeat('    ', $indent);
            $isList = array_is_list($value);
            $lines = [];

            foreach ($value as $key => $item) {
                $line = $pad.($isList ? '' : self::export($key).' => ').self::export($item, $indent + 1).',';

                if (isset($comments[$key])) {
                    $line .= ' // '.$comments[$key];
                }

                $lines[] = $line;
            }

            return "[\n".implode("\n", $lines)."\n".str_repeat('    ', $indent - 1).']';
        }

        return match (true) {
            $value === null => 'null',
            $value === true => 'true',
            $value === false => 'false',
            is_int($value) => (string) $value,
            is_float($value) => var_export($value, true),
            is_string($value) => self::exportString($value),
            default => throw new RuntimeException('Cannot export '.get_debug_type($value)),
        };
    }

    public static function exportString(string $value): string
    {
        if (preg_match('/[\x00-\x1F\x7F]/', $value) === 1) {
            $escaped = strtr($value, ['\\' => '\\\\', '"' => '\\"', '$' => '\\$', "\n" => '\\n', "\r" => '\\r', "\t" => '\\t', "\v" => '\\v', "\f" => '\\f', "\x1B" => '\\e']);

            return '"'.preg_replace_callback('/[\x00-\x1F\x7F]/', static fn (array $m): string => sprintf('\\x%02X', ord($m[0])), $escaped).'"';
        }

        return "'".strtr($value, ['\\' => '\\\\', "'" => "\\'"])."'";
    }

    /**
     * Turn a tagged spec value (@map, @set, @token, ...) into plain PHP data.
     *
     * Token types become ints, expression classes become PHP class names, sets become lists.
     */
    public static function decode(mixed $value, TokenTypes $tokens): mixed
    {
        if (! is_array($value)) {
            return $value;
        }

        if (array_is_list($value)) {
            return array_map(static fn (mixed $item): mixed => self::decode($item, $tokens), $value);
        }

        return match (true) {
            isset($value['@token']) => $tokens->value($value['@token']),
            isset($value['@dtype']) => $value['@dtype'],
            isset($value['@exp']) => Expressions::phpName($value['@exp']),
            isset($value['@enum']) => $value['@enum'],
            array_key_exists('@map', $value) => self::decodeMap($value['@map'], $tokens),
            array_key_exists('@set', $value) => array_map(static fn (mixed $item): mixed => self::decode($item, $tokens), $value['@set']),
            default => $value,
        };
    }

    /**
     * @param  list<array{0: mixed, 1: mixed}>  $entries
     * @return array<array-key, mixed>
     */
    public static function decodeMap(array $entries, TokenTypes $tokens): array
    {
        $map = [];

        foreach ($entries as [$key, $item]) {
            $key = self::decode($key, $tokens);

            if (! is_int($key) && ! is_string($key)) {
                throw new RuntimeException('Unsupported map key '.json_encode($key));
            }

            $map[$key] = self::decode($item, $tokens);
        }

        return $map;
    }
}
